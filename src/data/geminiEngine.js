export function evaluateMathExpression(rawQuery) {
  const clean = rawQuery
    .replace(/[?।!,]/g, '')
    .replace(/\s+/g, ' ')
    .trim();

  // Percentage: e.g. "500 এর 15%" or "15% of 800"
  const percentMatch1 = clean.match(/^(\d+(?:\.\d+)?)\s*(?:এর|of)\s*(\d+(?:\.\d+)?)\s*%/i);
  const percentMatch2 = clean.match(/^(\d+(?:\.\d+)?)\s*%\s*(?:এর|of)\s*(\d+(?:\.\d+)?)/i);
  if (percentMatch1 || percentMatch2) {
    const base = parseFloat(percentMatch1 ? percentMatch1[1] : percentMatch2[2]);
    const rate = parseFloat(percentMatch1 ? percentMatch1[2] : percentMatch2[1]);
    const result = (base * rate) / 100;
    return `### শতকরা নির্ণয় (Percentage Calculation)

**প্রশ্ন:** ${base}-এর ${rate}% কত?

#### সমাধানের ধাপ:
\`\`\`
ফলাফল = (${base} × ${rate}) / 100
      = ${base * rate} / 100
      = ${result}
\`\`\`

**উত্তর:** **${base}**-এর **${rate}%** হলো **${result}**।`;
  }

  // Circle area: e.g. "ব্যাসার্ধ 7 হলে ক্ষেত্রফল"
  const circleMatch = clean.match(/ব্যাসার্ধ\s*(\d+(?:\.\d+)?)/i);
  if (circleMatch && (clean.includes('ক্ষেত্রফল') || clean.includes('area'))) {
    const r = parseFloat(circleMatch[1]);
    const area = (Math.PI * r * r).toFixed(2);
    const perimeter = (2 * Math.PI * r).toFixed(2);
    return `### বৃত্তের ক্ষেত্রফল ও পরিধি (Circle Area & Circumference)

দেওয়া আছে, বৃত্তের ব্যাসার্ধ $r = ${r}$ একক।

#### ১. ক্ষেত্রফলের হিসাব:
\`\`\`
ক্ষেত্রফল A = π × r²
           ≈ 3.1416 × (${r})²
           ≈ ${area} বর্গ একক
\`\`\`

#### ২. পরিধির হিসাব:
\`\`\`
পরিধি C = 2 × π × r
        ≈ 2 × 3.1416 × ${r}
        ≈ ${perimeter} একক
\`\`\`

**উত্তর:** বৃত্তটির ক্ষেত্রফল প্রায় **${area}** বর্গ একক এবং পরিধি **${perimeter}** একক।`;
  }

  // Arithmetic: e.g. "25 * 14", "100 / 4", "50 + 75", "120 - 45", "2^8", "sqrt(144)"
  const sqrtMatch = clean.match(/^(?:sqrt|বর্গমূল)\s*\(?(\d+(?:\.\d+)?)\)?$/i);
  if (sqrtMatch) {
    const val = parseFloat(sqrtMatch[1]);
    const res = Math.sqrt(val);
    return `### বর্গমূল নির্ণয় (Square Root)
\`\`\`
√${val} = ${res}
\`\`\`
**উত্তর:** ${val}-এর বর্গমূল হলো **${res}**।`;
  }

  const basicMathMatch = clean.match(/(\d+(?:\.\d+)?)\s*([\+\-\*\/x×÷\^])\s*(\d+(?:\.\d+)?)/i);
  if (basicMathMatch) {
    const num1 = parseFloat(basicMathMatch[1]);
    let op = basicMathMatch[2];
    const num2 = parseFloat(basicMathMatch[3]);
    let result = 0;

    if (op === '+' ) result = num1 + num2;
    else if (op === '-') result = num1 - num2;
    else if (op === '*' || op.toLowerCase() === 'x' || op === '×') {
      result = num1 * num2;
      op = '×';
    }
    else if (op === '/' || op === '÷') {
      if (num2 === 0) return 'কোনো সংখ্যাকে শূন্য (০) দিয়ে ভাগ করা অসংজ্ঞায়িত (Undefined)!';
      result = Number((num1 / num2).toFixed(4));
      op = '÷';
    }
    else if (op === '^') {
      result = Math.pow(num1, num2);
    }

    return `### গাণিতিক হিসাব সমাধান

\`\`\`
${num1} ${op} ${num2} = ${result}
\`\`\`

**নির্ণেয় ফলাফল:** **${result}**

তোমার কি আরও কোনো হিসাব বা গাণিতিক সমীকরণ সমাধান করতে হবে? নির্দ্বিধায় লিখে জানাও!`;
  }

  // Linear equation solver: e.g. "2x + 5 = 15", "3x - 9 = 0", "5x = 20"
  const linearMatch = clean.match(/(\d*)x\s*([\+\-])\s*(\d+)\s*=\s*(\d+)/i);
  if (linearMatch) {
    const a = linearMatch[1] === '' ? 1 : parseInt(linearMatch[1]);
    const sign = linearMatch[2];
    const b = parseInt(linearMatch[3]);
    const c = parseInt(linearMatch[4]);

    const rhs = sign === '+' ? c - b : c + b;
    const x = rhs / a;

    return `### রৈখিক সমীকরণ সমাধান (Linear Equation)

দেওয়া আছে সমীকরণ:
\`\`\`
${a}x ${sign} ${b} = ${c}
\`\`\`

#### ধাপ ১: ধ্রুবক পদ পক্ষান্তর করে:
\`\`\`
${a}x = ${c} ${sign === '+' ? '-' : '+'} ${b}
${a}x = ${rhs}
\`\`\`

#### ধাপ ২: $x$-এর মান নির্ণয়:
\`\`\`
x = ${rhs} / ${a}
x = ${x}
\`\`\`

**উত্তর:** সমীকরণের নির্ণেয় মূল: **x = ${x}**।`;
  }

  const simpleLinear = clean.match(/(\d*)x\s*=\s*(\d+)/i);
  if (simpleLinear) {
    const a = simpleLinear[1] === '' ? 1 : parseInt(simpleLinear[1]);
    const c = parseInt(simpleLinear[2]);
    const x = c / a;
    return `### সমীকরণ সমাধান
\`\`\`
${a}x = ${c}
x = ${c} / ${a}
x = ${x}
\`\`\`
**উত্তর:** **x = ${x}**।`;
  }

  return null;
}

