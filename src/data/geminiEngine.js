export async function askGeminiAI(userPrompt, subject = 'all', mode = 'concept', attachment = null, chatHistory = []) {
  const query = (userPrompt || '').trim();
  const normalized = query.toLowerCase();

  // 1. QUIZ REQUEST DETECTION -> ALWAYS SERVE 20 QUESTIONS
  if (
    mode === 'quiz' ||
    normalized.includes('কুইজ') ||
    normalized.includes('quiz') ||
    normalized.includes('mcq') ||
    normalized.includes('মডেল টেস্ট') ||
    normalized.includes('test') ||
    normalized.includes('২০ প্রশ্ন') ||
    normalized.includes('20 question')
  ) {
    let targetSubj = subject;
    if (targetSubj === 'all') {
      const subjKeywords = {
        math: ['math', 'গণিত', 'অঙ্ক', 'বীজগণিত', 'জ্যামিতি'],
        physics: ['physics', 'পদার্থ', 'গতি', 'আলো'],
        chemistry: ['chemistry', 'রসায়ন', 'রাসায়নিক'],
        biology: ['biology', 'জীববিজ্ঞান', 'উদ্ভিদ'],
        ict: ['ict', 'আইসিটি', 'কোডিং', 'পাইথন', 'লজিক'],
        english: ['english', 'ইংরেজি', 'grammar'],
        bangla: ['bangla', 'বাংলা', 'সমাস', 'সাহিত্য'],
        school: ['school', 'ক্যাম্পাস', 'সাধারণ জ্ঞান']
      };
      for (const [sKey, kws] of Object.entries(subjKeywords)) {
        if (kws.some(k => normalized.includes(k))) {
          targetSubj = sKey;
          break;
        }
      }
    }

    const quizList = getTwentyQuestionsForSubject(targetSubj);
    const subjNames = {
      math: 'গণিত (Mathematics)',
      physics: 'পদার্থবিজ্ঞান (Physics)',
      chemistry: 'রসায়ন (Chemistry)',
      biology: 'জীববিজ্ঞান (Biology)',
      ict: 'আইসিটি ও কোডিং (ICT)',
      english: 'ইংরেজি (English)',
      bangla: 'বাংলা ব্যাকরণ (Bangla)',
      school: 'ক্যাম্পাস ও সাধারণ জ্ঞান',
      all: 'সকল বিষয় (Combined Model Test)'
    };

    return {
      type: 'quiz_set_20',
      title: ` ২০টি বহুনির্বাচনী কুইজ মডেল টেস্ট: ${subjNames[targetSubj] || 'সকল বিষয়'}`,
      subject: targetSubj,
      subjectName: subjNames[targetSubj] || 'সকল বিষয়',
      quizSet: quizList,
      totalCount: 20,
      content: `চমৎকার চ্যালেঞ্জ! তোমার অনুরোধ অনুযায়ী এক সাথে ২০টি বহুনির্বাচনী প্রশ্ন (MCQ) প্রস্তুত করা হয়েছে। প্রতিটি প্রশ্ন সমাধান করে সাবমিট করো, সাথে সাথে সম্পূর্ণ ফলাফল, গ্রেড এবং প্রতিটি প্রশ্নের বিশদ ব্যাখ্যা পেয়ে যাবে!`
    };
  }

  // 2. CHECK OPTIONAL REAL GOOGLE GEMINI API KEY (if configured in environment or localStorage)
  const geminiApiKey =
    (typeof window !== 'undefined' && localStorage.getItem('gemini_api_key')) ||
    (typeof import.meta !== 'undefined' && import.meta.env?.VITE_GEMINI_API_KEY) ||
    (typeof process !== 'undefined' && process.env?.GEMINI_API_KEY);

  if (geminiApiKey) {
    try {
      let parts = [];
      if (attachment?.dataUrl) {
        const mimeType = attachment.type || (attachment.fileType === 'pdf' ? 'application/pdf' : 'image/jpeg');
        const base64Data = attachment.dataUrl.includes(',') 
          ? attachment.dataUrl.split(',')[1] 
          : attachment.dataUrl;

        if (base64Data) {
          parts.push({
            inlineData: {
              mimeType: mimeType,
              data: base64Data
            }
          });
        }
      }

      parts.push({
        text: `You are Tanzim AI, an elite AI Professor for Ideal School & College students (classes 6-12 NCTB curriculum). 
Answer the following student query directly, intelligently, and clearly using clean markdown formatting (headings, bullet points, math expressions, bold terms). 
Respond in Bengali if the prompt is in Bengali or Banglish, otherwise in English.
Student Prompt: ${query || 'Please analyze and solve the attached file in detail.'}`
      });

      const apiResp = await fetch(
        `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${geminiApiKey}`,
        {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ contents: [{ parts }] })
        }
      );

      if (apiResp.ok) {
        const data = await apiResp.json();
        const geminiText = data?.candidates?.[0]?.content?.parts?.[0]?.text;
        if (geminiText) {
          return {
            type: 'text',
            title: 'Tanzim AI',
            content: geminiText
          };
        }
      }
    } catch (err) {
      console.warn('Gemini API call error, falling back to OpenAI Cloud:', err);
    }
  }

  // 3. CHECK OPTIONAL OPENAI API KEY (if configured in localStorage or environment)
  const openaiApiKey =
    (typeof window !== 'undefined' && localStorage.getItem('openai_api_key')) ||
    (typeof import.meta !== 'undefined' && import.meta.env?.VITE_OPENAI_API_KEY) ||
    (typeof process !== 'undefined' && process.env?.OPENAI_API_KEY);

  if (openaiApiKey) {
    try {
      const openAiResp = await fetch('https://api.openai.com/v1/chat/completions', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'Authorization': `Bearer ${openaiApiKey}`
        },
        body: JSON.stringify({
          model: 'gpt-4o-mini',
          messages: [
            {
              role: 'system',
              content: 'You are Tanzim AI, an expert AI created for Bangladeshi students. Answer directly, intelligently, accurately, and in clean markdown.'
            },
            { role: 'user', content: query }
          ]
        })
      });
      if (openAiResp.ok) {
        const data = await openAiResp.json();
        const text = data?.choices?.[0]?.message?.content;
        if (text) {
          return {
            type: 'text',
            title: 'Tanzim AI',
            content: text
          };
        }
      }
    } catch (err) {
      console.warn('OpenAI official API call error:', err);
    }
  }

  // 4. ONLINE OPENAI INTELLIGENCE ENGINE (Zero Key Required, 100% Free & Fast with Multi-turn Memory)
  try {
    const cloudAiResponse = await fetchOpenAICloudResponse(query, subject, attachment, chatHistory);
    if (cloudAiResponse) {
      return cloudAiResponse;
    }
  } catch (err) {
    console.warn('Online OpenAI engine error, using local fallback:', err);
  }

  // 5. ATTACHMENT FALLBACK (If attachment present and online failed)
  if (attachment) {
    return analyzeUploadedAttachment(query, attachment, subject);
  }

  // 6. DYNAMIC ARITHMETIC & EQUATION EVALUATOR
  const mathResult = evaluateMathExpression(query);
  if (mathResult) {
    return {
      type: 'text',
      title: 'Tanzim AI • গাণিতিক সমাধান',
      content: mathResult
    };
  }

  // 7. CONVERSATIONAL, SLANG, EMOTIONAL & COMPLAINT HANDLING
  const convResponse = handleConversationalQuery(normalized);
  if (convResponse) {
    return convResponse;
  }

  // 8. CURATED TOPIC REGISTRY (100+ Topics across all subjects)
  for (const topic of TOPIC_REGISTRY) {
    if (topic.patterns.some(p => normalized.includes(p.toLowerCase()))) {
      return {
        type: 'text',
        title: 'Tanzim AI',
        content: topic.generate(query)
      };
    }
  }

  // 9. LOCAL INTELLIGENT DEEP SYNTHESIZER
  return synthesizeDynamicGeminiResponse(query, subject);
}


